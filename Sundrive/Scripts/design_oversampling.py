#!/usr/bin/env python3
"""Regenerate the checked-in low-latency FIR; not needed to build the plugin.

Requires NumPy and SciPy >= 1.14. The full-length minimum-phase conversion
preserves the v1.0 prototype's magnitude rather than taking its square root.
Reference: https://docs.scipy.org/doc/scipy/reference/generated/scipy.signal.minimum_phase.html
"""
from pathlib import Path
import argparse
import json
import numpy as np
from scipy import signal


def main():
    root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=root / "Source/OversamplingFilter.h")
    parser.add_argument("--report", type=Path, default=root / "Tests/Oversampling-design.json")
    args = parser.parse_args()

    prototype = signal.firwin(129, 0.225, window="blackman")
    minimum = signal.minimum_phase(prototype, method="homomorphic", n_fft=262144, half=False)
    minimum /= minimum.sum()
    # The plugin decimates at phase 0. Calibrate the actual base-rate kernel,
    # including any residual image terms, instead of rounding its peak.
    kernel = 4 * np.convolve(minimum, minimum)[::4]
    dc_delay = float(np.dot(np.arange(len(kernel)), kernel) / kernel.sum())
    latency = int(np.ceil(dc_delay))
    fractional_delay = latency - dc_delay
    alignment_coefficient = (1 - fractional_delay) / (1 + fractional_delay)
    aligned_impulse = signal.lfilter([alignment_coefficient, 1],
                                    [1, alignment_coefficient],
                                    np.r_[kernel, np.zeros(512)])
    assert latency == 5 and 0 <= fractional_delay < 1

    w, old_response = signal.freqz(prototype, worN=131072)
    _, new_response = signal.freqz(minimum, worN=w)
    passband = w / np.pi <= 0.20
    stopband = w / np.pi >= 0.30
    difference = float(np.max(np.abs(20 * np.log10(
        np.abs(new_response[passband]) / np.abs(old_response[passband])))))
    assert difference < 0.001

    values = "\n".join("    " + ", ".join(f"{v:.17g}" for v in minimum[i:i+3]) + ","
                       for i in range(0, len(minimum), 3))
    header = f'''#pragma once
// Generated by Scripts/design_oversampling.py. No Python dependency at runtime.
// Full-length minimum-phase conversion of the v1.0 129-tap Blackman prototype.
// A fractional allpass aligns its low-frequency delay to {latency} base-rate samples.
#include <array>
namespace sundrive::oversampling_filter {{
inline constexpr int taps = {len(minimum)};
inline constexpr int latency = {latency};
inline constexpr double dcDelayBeforeAlignment = {dc_delay:.17g};
inline constexpr double alignmentCoefficient = {alignment_coefficient:.17g};
inline constexpr std::array<double, taps> coefficients = {{{{
{values}
}}}};
}}
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(header, encoding="utf-8")
    report = {
        "design": "Full-length minimum-phase FIR, 4x oversampling",
        "taps_per_filter": len(minimum),
        "reported_latency_samples": latency,
        "previous_latency_samples": 32,
        "dc_delay_before_alignment_samples": dc_delay,
        "fractional_alignment_delay_samples": fractional_delay,
        "alignment_allpass_coefficient": alignment_coefficient,
        "identity_impulse_peak_samples": int(np.argmax(np.abs(aligned_impulse))),
        "maximum_single_filter_magnitude_difference_db": difference,
        "comparison_band_high_rate_nyquist_fraction": [0, 0.20],
        "stopband_high_rate_nyquist_fraction": [0.30, 1],
        "previous_worst_stopband_db": float(20*np.log10(np.max(np.abs(old_response[stopband])))),
        "updated_worst_stopband_db": float(20*np.log10(np.max(np.abs(new_response[stopband])))),
        "notes": "Minimum-phase filters have frequency-dependent phase delay; the host value is aligned at DC."
    }
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()
